const DICT: Record<Lang, Record<Key, string>> = { en, zh };

export type TFunc = (key: Key, vars?: Record<string, string | number>) => string;

function translate(lang: Lang, key: Key, vars?: Record<string, string | number>): string {
  const s = DICT[lang][key] ?? en[key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : s;
}

// ---- persisted preferences ----

const PREFS_KEY = 'ht.prefs';
interface Prefs {
  lang: Lang;
  theme: Theme;
  palette: PaletteId;
  /** Your name as this app shows it; empty = the default "You". Display only: agents never see it. */
  userName: string;
}
export const USER_NAME_MAX = 40;
const DEFAULT_PREFS: Prefs = { lang: 'en', theme: 'system', palette: 'default', userName: '' };

function loadPrefs(): Prefs {
  try {
    const v = JSON.parse(localStorage.getItem(PREFS_KEY) ?? 'null') as Partial<Prefs> | null;
    return {
      lang: v?.lang === 'zh' || v?.lang === 'en' ? v.lang : DEFAULT_PREFS.lang,
      theme: v?.theme === 'light' || v?.theme === 'dark' || v?.theme === 'system' ? v.theme : DEFAULT_PREFS.theme,
      palette: isPaletteId(v?.palette) ? v.palette : DEFAULT_PREFS.palette,
      userName: typeof v?.userName === 'string' ? v.userName.slice(0, USER_NAME_MAX) : DEFAULT_PREFS.userName,
    };
  } catch {
    return DEFAULT_PREFS;
  }
}

/** Your own avatar: a small square image as a data URL, kept apart from the other preferences (it is much larger). */
const AVATAR_KEY = 'ht.avatar';

function loadAvatar(): string | null {
  try {
    const v = localStorage.getItem(AVATAR_KEY);
    return v && v.startsWith('data:image/') ? v : null;
  } catch {
    return null;
  }
}

function savePrefs(p: Prefs) {
  try {
    localStorage.setItem(PREFS_KEY, JSON.stringify(p));
  } catch {
    // preferences are a per-window convenience
  }
}

interface PrefsContext extends Prefs {
  t: TFunc;
  locale: string;
  setLang: (l: Lang) => void;
  setTheme: (t: Theme) => void;
  setPalette: (p: PaletteId) => void;
  setUserName: (name: string) => void;
  /** The name shown for you: your own name, or the default "You". */
  userLabel: string;
  /** Your avatar image (data URL), or null for the default letter. */
  userAvatar: string | null;
  /** Saves (or with null removes) your avatar on this device. Returns false when the browser storage refused it. */
  setUserAvatar: (dataUrl: string | null) => boolean;
  /** Whether the dark tone is in effect (explicit choice or the system setting). */
  dark: boolean;
}

const darkQuery = (): MediaQueryList | null =>
  typeof window !== 'undefined' && window.matchMedia ? window.matchMedia('(prefers-color-scheme: dark)') : null;

function useSystemDark(): boolean {
  const [dark, setDark] = useState(() => darkQuery()?.matches ?? false);
  useEffect(() => {
    const q = darkQuery();
    if (!q) return;
    const on = () => setDark(q.matches);
    q.addEventListener('change', on);
    return () => q.removeEventListener('change', on);
  }, []);
  return dark;
}

const Ctx = createContext<PrefsContext | null>(null);

/** UI language for code outside React (error texts); kept in step with the provider. */
let currentLang: Lang = DEFAULT_PREFS.lang;
export const activeLang = (): Lang => currentLang;

export function PrefsProvider({ children }: { children: ReactNode }) {
  const [prefs, setPrefs] = useState<Prefs>(loadPrefs);
  currentLang = prefs.lang;
  const [userAvatar, setAvatarState] = useState<string | null>(loadAvatar);
  const systemDark = useSystemDark();
  const dark = prefs.theme === 'dark' || (prefs.theme === 'system' && systemDark);
  // Layout effect: apply colors before paint so switching (and first load) does not flash the default palette.
  useLayoutEffect(() => {
    savePrefs(prefs);
    const root = document.documentElement;
    root.lang = prefs.lang === 'zh' ? 'zh-CN' : 'en';
    if (prefs.theme === 'system') root.removeAttribute('data-theme');
    else root.setAttribute('data-theme', prefs.theme);
    const vars = paletteVars(prefs.palette, dark);
    for (const name of PALETTE_VAR_NAMES) root.style.removeProperty(name);
    if (vars) for (const [name, v] of Object.entries(vars)) root.style.setProperty(name, v);
    root.dataset.palette = prefs.palette;
  }, [prefs, dark]);
  const value = useMemo<PrefsContext>(
    () => ({
      ...prefs,
      dark,
      locale: prefs.lang === 'zh' ? 'zh-CN' : 'en-US',
      t: (key, vars) => translate(prefs.lang, key, vars),
      setLang: (lang) => setPrefs((p) => ({ ...p, lang })),
      setTheme: (theme) => setPrefs((p) => ({ ...p, theme })),
      setPalette: (palette) => setPrefs((p) => ({ ...p, palette })),
      setUserName: (userName) => setPrefs((p) => ({ ...p, userName: userName.slice(0, USER_NAME_MAX) })),
      userLabel: prefs.userName.trim() || translate(prefs.lang, 'common.you'),
      userAvatar,
      setUserAvatar: (dataUrl) => {
        try {
          if (dataUrl) localStorage.setItem(AVATAR_KEY, dataUrl);
          else localStorage.removeItem(AVATAR_KEY);
        } catch {
          return false;
        }
        setAvatarState(dataUrl);
        return true;
      },
    }),
    [prefs, dark, userAvatar],
  );
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function usePrefs(): PrefsContext {
  const c = useContext(Ctx);
  if (!c) throw new Error('usePrefs outside PrefsProvider');
  return c;
}

export const useT = (): TFunc => usePrefs().t;

/**
 * Server text in the UI language: messages carry a code + params next to their Chinese body. Falls back to the body
 * for older messages and for codes this build does not know.
 */
export function useNoticeText(): (n: NoticeText | null | undefined, fallback: string) => string {
  const { lang } = usePrefs();
  return (n, fallback) => (isNotice(n) ? renderNotice(n, lang) : fallback);
}

/** Renders a Localized value (plain text or a NoticeText from the server) in the UI language. */
export function useLocalized(): (v: Localized | null | undefined) => string {
  const { lang } = usePrefs();
  return (v) => (v === null || v === undefined ? '' : typeof v === 'string' ? v : isNotice(v) ? renderNotice(v, lang) : '');
}
